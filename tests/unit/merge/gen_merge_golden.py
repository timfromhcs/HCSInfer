"""Generates merge_golden.inc: golden outputs of every merge method computed with numpy (float64) from
float32 inputs, following the definitions documented in include/hcs/merge.hpp. The C++ tests compare the
streaming engine against these values. Run with a venv that has numpy:

    python gen_merge_golden.py > merge_golden.inc
"""
import math
import numpy as np

M = (1 << 64) - 1
GOLD = 0x9E3779B97F4A7C15


def fnv1a64(s):
    h = 0xCBF29CE484222325
    for c in s.encode():
        h ^= c
        h = (h * 0x100000001B3) & M
    return h


def uniform(seed, key, model, idx):
    k = seed ^ key ^ ((model * 0xD6E8FEB86659FD93) & M)
    z = (k + ((idx + 1) * GOLD)) & M
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M
    z ^= z >> 31
    return (z >> 11) * (1.0 / 9007199254740992.0)


def linear(arrs, w):
    return sum(wi * a for wi, a in zip(w, arrs)) / sum(w)


def slerp(a, b, t):
    na, nb = np.linalg.norm(a), np.linalg.norm(b)
    if na == 0 or nb == 0:
        return (1 - t) * a + t * b
    d = float(np.dot(a, b) / (na * nb))
    if abs(d) > 0.9995:
        return (1 - t) * a + t * b
    th = math.acos(max(-1.0, min(1.0, d)))
    s = math.sin(th)
    return math.sin((1 - t) * th) / s * a + math.sin(t * th) / s * b


def ties(base, models, w, density, lam):
    n = base.size
    k = max(1, math.ceil(density * n))
    weighted = []
    for m, wi in zip(models, w):
        d = m - base
        a = np.abs(d)
        thr = np.partition(a, n - k)[n - k]
        weighted.append(np.where(a >= thr, wi * d, 0.0))
    s = np.sum(weighted, axis=0)
    elected = np.sign(s)
    num = np.zeros_like(base)
    den = np.zeros_like(base)
    for wt, wi in zip(weighted, w):
        mask = (np.sign(wt) == elected) & (elected != 0)
        num += np.where(mask, wt, 0.0)
        den += np.where(mask, wi, 0.0)
    merged = np.where(den > 0, num / np.where(den > 0, den, 1.0), 0.0)
    return base + lam * merged


def dare(base, models, w, p, seed, name, first=0):
    key = fnv1a64(name)
    acc = np.zeros_like(base)
    for mi, (m, wi) in enumerate(zip(models, w)):
        keep = np.array([uniform(seed, key, mi, first + i) >= p for i in range(base.size)])
        acc += np.where(keep, wi * (m - base) / (1.0 - p), 0.0)
    return base + 1.0 * acc


def lora(base, A, B, scale):
    return base + scale * (B @ A)


def emit(name, arr):
    flat = np.asarray(arr).reshape(-1)
    print("static const std::vector<float> %s = {%s};" % (name, ", ".join("%.9ef" % np.float32(v) for v in flat)))


rng = np.random.default_rng(20261126)
n = 32
base = rng.standard_normal(n).astype(np.float32)
m1 = (base + 0.5 * rng.standard_normal(n)).astype(np.float32)
m2 = (base + 0.5 * rng.standard_normal(n)).astype(np.float32)
b64, m164, m264 = base.astype(np.float64), m1.astype(np.float64), m2.astype(np.float64)

print("// Generated by gen_merge_golden.py (numpy %s). Do not edit." % np.__version__)
print("constexpr std::size_t kGoldenN = %d;" % n)
emit("kBase", base)
emit("kM1", m1)
emit("kM2", m2)
emit("kLinear", linear([b64, m164, m264], [0.5, 0.3, 0.2]))
emit("kSlerp", slerp(b64, m164, 0.3))
# near-parallel pair: exercises the lerp fallback
par = (base * 2.0).astype(np.float32)
emit("kPar", par)
emit("kSlerpParallel", slerp(b64, par.astype(np.float64), 0.25))
emit("kTies", ties(b64, [m164, m264], [1.0, 0.5], 0.25, 0.8))
emit("kDare", dare(b64, [m164, m264], [1.0, 0.5], 0.25, 99, "w.test"))
emit("kDareTail", dare(b64, [m164, m264], [1.0, 0.5], 0.25, 99, "w.test", first=0)[16:])

# LoRA: base 4x6, A 2x6, B 4x2, alpha 4, rank 2, strength 0.75 -> scale 0.75*4/2 = 1.5
lb = rng.standard_normal((4, 6)).astype(np.float32)
la = rng.standard_normal((2, 6)).astype(np.float32)
lbb = rng.standard_normal((4, 2)).astype(np.float32)
emit("kLoraBase", lb)
emit("kLoraA", la)
emit("kLoraB", lbb)
emit("kLoraOut", lora(lb.astype(np.float64), la.astype(np.float64), lbb.astype(np.float64), 0.75 * 4.0 / 2.0))

# fnv / uniform sanity values
print("constexpr std::uint64_t kFnvWTest = 0x%016XULL;" % fnv1a64("w.test"))
print("static const std::vector<double> kUniform = {%s};" % ", ".join("%.17g" % uniform(99, fnv1a64("w.test"), 1, i) for i in range(6)))
# float16 / bfloat16 reference conversions (numpy)
vals = np.array([0.0, 1.0, -2.5, 0.1, 65504.0, 70000.0, 1e-8, 6.1e-5, 5.96e-8, 3.14159265, -1234.5678, 0.333333333], dtype=np.float32)
print("static const std::vector<float> kHalfIn = {%s};" % ", ".join("%.9ef" % v for v in vals))
print("static const std::vector<unsigned> kHalfBits = {%s};" % ", ".join(str(int(v)) for v in vals.astype(np.float16).view(np.uint16)))
# bf16 by truncation with round-to-nearest-even on the float32 bits
bits = vals.view(np.uint32).astype(np.uint64)
rb = ((bits + 0x7FFF + ((bits >> 16) & 1)) >> 16).astype(np.uint32)
print("static const std::vector<unsigned> kBf16Bits = {%s};" % ", ".join(str(int(v)) for v in rb))
