"""Generates resample_golden.inc: an independent numpy implementation of the Lanczos-3 resampler defined in
include/hcs/upscale.hpp (support scales with the downsampling ratio, weights normalised, edge clamp, horizontal
then vertical pass, clamp to [0,1], round to 8 bit). Run with a venv that has numpy:

    python gen_resample_golden.py > resample_golden.inc
"""
import numpy as np


def lanczos3(x):
    x = np.abs(x)
    out = np.zeros_like(x, dtype=np.float64)
    nz = (x > 1e-12) & (x < 3.0)
    px = np.pi * x[nz]
    out[nz] = 3.0 * np.sin(px) * np.sin(px / 3.0) / (px * px)
    out[x <= 1e-12] = 1.0
    return out


def axis_matrix(n_in, n_out):
    scale = n_in / n_out
    fscale = max(1.0, scale)
    support = 3.0 * fscale
    m = np.zeros((n_out, n_in), dtype=np.float64)
    for o in range(n_out):
        c = (o + 0.5) * scale - 0.5
        lo = int(np.ceil(c - support))
        hi = int(np.floor(c + support))
        idx = np.arange(lo, hi + 1)
        w = lanczos3((idx - c) / fscale)
        w = w / w.sum()
        for i, wi in zip(idx, w):
            m[o, min(max(i, 0), n_in - 1)] += wi
    return m


def resample(img, out_w, out_h):
    h, w, _ = img.shape
    mx = axis_matrix(w, out_w)
    my = axis_matrix(h, out_h)
    mid = np.einsum("xw,hwc->hxc", mx, img.astype(np.float64))
    res = np.einsum("yh,hxc->yxc", my, mid)
    res = np.clip(res, 0.0, 1.0) * 255.0 + 0.5
    return np.floor(res).astype(np.int64)


def emit(name, arr, fmt):
    flat = arr.reshape(-1)
    body = ", ".join(fmt % v for v in flat)
    print("static const std::vector<%s> %s = {%s};" % ("float" if fmt.endswith("f") else "int", name, body))


rng = np.random.default_rng(1234)
W, H = 9, 7
img = rng.random((H, W, 3)).astype(np.float32)
up = resample(img, 23, 17)
down = resample(img, 4, 3)
print("// Generated by gen_resample_golden.py (numpy %s). Do not edit." % np.__version__)
print("constexpr std::uint32_t kGoldenInW = %d, kGoldenInH = %d, kGoldenUpW = 23, kGoldenUpH = 17, kGoldenDownW = 4, kGoldenDownH = 3;" % (W, H))
emit("kGoldenIn", img, "%.9ef")
emit("kGoldenUp", up, "%d")
emit("kGoldenDown", down, "%d")
